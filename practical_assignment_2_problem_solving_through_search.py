import time
import heapq
from collections import deque

# COLLEGE CAMPUS GRAPH
graph = {
    "Main Gate": {
        "Library": 120,
        "Canteen": 100,
        "Sports Ground": 200
    },
    "Library": {
        "Computer Lab": 200
    },
    "Canteen": {
        "Computer Lab": 180
    },
    "Sports Ground": {
        "Computer Lab": 100
    },
    "Computer Lab": {}
}

# HEURISTIC VALUES
# Estimated distance to Computer Lab

h = {
    "Main Gate": 200,
    "Library": 140,
    "Canteen": 90,
    "Sports Ground": 80,
    "Computer Lab": 0
}

# 1. BREADTH FIRST SEARCH

def bfs(start, goal):
    queue = deque([(start, [start], 0)])
    visited = set()
    nodes = 0
    while queue:

        current, path, cost = queue.popleft()
        nodes += 1

        if current == goal:
            return path, cost, nodes

        if current in visited:
            continue

        visited.add(current)

        for location, distance in graph[current].items():

            if location not in visited:

                queue.append(
                    (
                        location,
                        path + [location],
                        cost + distance
                    )
                )

    return None, 0, nodes

# 2. DEPTH FIRST SEARCH
def dfs(start, goal):

    stack = [(start, [start], 0)]
    visited = set()
    nodes = 0

    while stack:

        current, path, cost = stack.pop()
        nodes += 1

        if current == goal:
            return path, cost, nodes

        if current in visited:
            continue

        visited.add(current)

        neighbours = list(graph[current].items())
        neighbours.reverse()

        for location, distance in neighbours:

            if location not in visited:

                stack.append(
                    (
                        location,
                        path + [location],
                        cost + distance
                    )
                )

    return None, 0, nodes


# 3. GREEDY BEST-FIRST SEARCH
def greedy(start, goal):

    current = start
    path = [current]
    cost = 0
    visited = set()
    nodes = 0

    while current != goal:

        visited.add(current)
        nodes += 1

        candidates = [
            location
            for location in graph[current]
            if location not in visited
        ]

        if not candidates:
            return None, 0, nodes

        next_location = min(
            candidates,
            key=lambda location: h[location]
        )

        cost += graph[current][next_location]

        current = next_location
        path.append(current)

    nodes += 1

    return path, cost, nodes



# 4. A* SEARCH
def a_star(start, goal):

    priority_queue = [
        (h[start], 0, start, [start])
    ]

    best_cost = {
        start: 0
    }

    nodes = 0

    while priority_queue:

        f, g, current, path = heapq.heappop(priority_queue)

        nodes += 1

        if current == goal:
            return path, g, nodes

        for location, distance in graph[current].items():

            new_cost = g + distance

            if (
                location not in best_cost
                or new_cost < best_cost[location]
            ):

                best_cost[location] = new_cost

                new_f = new_cost + h[location]

                heapq.heappush(
                    priority_queue,
                    (
                        new_f,
                        new_cost,
                        location,
                        path + [location]
                    )
                )

    return None, 0, nodes



# 5. HILL CLIMBING
def hill_climbing(start, goal):

    current = start
    path = [current]
    cost = 0
    nodes = 0

    while current != goal:

        nodes += 1

        neighbours = list(
            graph[current].items()
        )

        if not neighbours:
            return None, 0, nodes

        next_location, distance = min(
            neighbours,
            key=lambda item: h[item[0]]
        )

        if h[next_location] >= h[current]:

            return None, cost, nodes

        cost += distance

        current = next_location

        path.append(current)

    nodes += 1

    return path, cost, nodes




# 6. N-QUEENS
def solve_n_queens(n):

    board = [-1] * n
    nodes = 0

    def is_safe(row, col):

        for previous_row in range(row):

            previous_col = board[previous_row]

            # Same column
            if previous_col == col:
                return False

            # Same diagonal
            if abs(previous_col - col) == abs(
                previous_row - row
            ):
                return False

        return True


    def backtrack(row):

        nonlocal nodes

        nodes += 1

        if row == n:
            return True

        for col in range(n):

            if is_safe(row, col):

                board[row] = col

                if backtrack(row + 1):
                    return True

                board[row] = -1

        return False


    start_time = time.perf_counter()

    solved = backtrack(0)

    end_time = time.perf_counter()

    return (
        solved,
        board,
        nodes,
        end_time - start_time
    )


